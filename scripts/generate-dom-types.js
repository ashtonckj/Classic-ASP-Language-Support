#!/usr/bin/env node
/**
 * generate-dom-types.js
 *
 * Bakes src/utils/asp-dom.d.ts into src/utils/aspDomTypes.generated.ts.
 *
 * The JS language service serves the ambient browser declarations to TypeScript
 * as a virtual file, so it needs them as a string at runtime. Two ways to get
 * them there, and this is the safer one:
 *
 *   • Read the .d.ts from disk when the extension starts. That is what the code
 *     used to do, and it never worked: tsc does not copy a .d.ts input into
 *     outDir, and .vscodeignore excludes src/** from the package, so the file
 *     reached neither development nor production. The silent fallback meant
 *     nobody noticed for a long time.
 *   • Bake it into the compiled output, which is what this script does. There is
 *     no runtime file read, so there is nothing to go missing from the package.
 *
 * Keeping the source of truth as a real .d.ts is what buys the type checking:
 * tsc compiles asp-dom.d.ts along with everything else in src/, so a declaration
 * that clashes with lib.dom.d.ts fails the build with a line number.
 *
 * Usage:
 *   node scripts/generate-dom-types.js            generate once
 *   node scripts/generate-dom-types.js --watch    generate, then on every change
 *
 * `npm run compile` runs the one-shot form. `npm run watch` runs the watching
 * form alongside tsc (see scripts/watch.js), because tsc -watch has no idea this
 * file needs regenerating — without it, editing the .d.ts mid-session would
 * silently do nothing, which is the exact trap this whole arrangement exists to
 * avoid. The generated file is committed so a fresh clone and `tsc -watch` work
 * before any script has run.
 */

const fs = require('fs');
const path = require('path');

const root   = path.resolve(__dirname, '..');
const SOURCE = path.join(root, 'src', 'utils', 'asp-dom.d.ts');
const TARGET = path.join(root, 'src', 'utils', 'aspDomTypes.generated.ts');

const rel = (p) => path.relative(root, p);

/** Builds the .ts wrapper for the given declaration text. */
function render(declarations) {
    // JSON.stringify does the escaping, so the declarations can contain
    // backticks, ${...} and backslashes without anyone having to think about it.
    return [
        '// AUTO-GENERATED by scripts/generate-dom-types.js — do not edit.',
        '// Edit src/utils/asp-dom.d.ts instead, then run `npm run compile`.',
        '',
        '/**',
        ' * Ambient browser declarations served to the TypeScript language service as a',
        ' * virtual file, so the JavaScript inside <script> blocks is checked against the',
        ' * browser APIs Classic ASP pages actually use.',
        ' */',
        `export const ASP_DOM_TYPES: string = ${JSON.stringify(declarations)};`,
        '',
    ].join('\n');
}

/**
 * Regenerates the target when it differs from the source.
 * Returns true when the file was rewritten.
 */
function generate({ quiet = false } = {}) {
    if (!fs.existsSync(SOURCE)) {
        console.error(`[asp] cannot generate DOM types: ${rel(SOURCE)} is missing`);
        return false;
    }

    const declarations = fs.readFileSync(SOURCE, 'utf8');
    const contents = render(declarations);

    // Only write when the content differs, so tsc -watch is not retriggered on
    // every run and the file's mtime stays meaningful.
    if (fs.existsSync(TARGET) && fs.readFileSync(TARGET, 'utf8') === contents) {
        if (!quiet) { console.log(`[asp] ${rel(TARGET)} already up to date`); }
        return false;
    }

    fs.writeFileSync(TARGET, contents, 'utf8');
    console.log(`[asp] generated ${rel(TARGET)} from ${rel(SOURCE)} (${declarations.length} chars)`);
    return true;
}

/**
 * Generates once, then again on every change to the declaration file.
 *
 * Editors write by replacing the file rather than modifying it in place, which
 * breaks a plain fs.watch on the path, so the watch is on the DIRECTORY and
 * filtered by name. Changes are debounced because one save commonly fires
 * several events.
 */
function watch() {
    generate();
    console.log(`[asp] watching ${rel(SOURCE)} for changes`);

    let pending;
    fs.watch(path.dirname(SOURCE), (_event, filename) => {
        if (filename !== path.basename(SOURCE)) { return; }
        clearTimeout(pending);
        pending = setTimeout(() => {
            try {
                generate({ quiet: true });
            } catch (err) {
                console.error(`[asp] failed to regenerate DOM types: ${err.message}`);
            }
        }, 100);
    });
}

if (require.main === module) {
    if (process.argv.includes('--watch')) {
        watch();
    } else if (!generate()) {
        // A missing source file is the only failure worth stopping the build for.
        if (!fs.existsSync(SOURCE)) { process.exit(1); }
    }
}

module.exports = { generate, watch, SOURCE, TARGET };
